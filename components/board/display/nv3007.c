esp_err_t board_panel_create(esp_lcd_panel_io_handle_t io,
                             esp_lcd_panel_handle_t *out_panel)
{
    const st7796_vendor_config_t vendor = {
        .init_cmds = k_init,
        .init_cmds_size = sizeof(k_init) / sizeof(k_init[0]),
    };
    const esp_lcd_panel_dev_config_t panel_config = {
        .reset_gpio_num = board_panel_reset_gpio(),
        .rgb_ele_order = TFT_RGB_ORDER_BGR ? LCD_RGB_ELEMENT_ORDER_BGR :
                                             LCD_RGB_ELEMENT_ORDER_RGB,
        .bits_per_pixel = 16,
        .vendor_config = (void *)&vendor,
    };
    esp_lcd_panel_handle_t panel = NULL;
    ESP_RETURN_ON_ERROR(esp_lcd_new_panel_st7796(io, &panel_config, &panel), TAG,
                        "create NV3007 panel failed");
    ESP_RETURN_ON_ERROR(esp_lcd_panel_reset(panel), TAG, "reset NV3007 failed");
    ESP_RETURN_ON_ERROR(esp_lcd_panel_init(panel), TAG, "initialize NV3007 failed");
    ESP_RETURN_ON_ERROR(esp_lcd_panel_invert_color(panel, TFT_INVERT_COLOR != 0), TAG,
                        "set NV3007 inversion failed");
    *out_panel = panel;
    return ESP_OK;
}

