typedef struct {
    const uint8_t *data;
    size_t length;
    size_t offset;
    uint16_t pixel;
    bool seen;
} probe_t;

static size_t feed(JDEC *decoder, uint8_t *buffer, size_t length)
{
    probe_t *probe = (probe_t *)decoder->device;
    const size_t left = probe->length - probe->offset;
    const size_t take = length < left ? length : left;
    if (buffer != NULL) memcpy(buffer, probe->data + probe->offset, take);
    probe->offset += take;
    return take;
}

static int collect(JDEC *decoder, void *bitmap, JRECT *rect)
{
    probe_t *probe = (probe_t *)decoder->device;
    (void)rect;
    if (!probe->seen) {
        probe->pixel = ((const uint16_t *)bitmap)[0];
        probe->seen = true;
    }
    return 1;
}

int main(void)
{
    static uint8_t work[4096];
    probe_t probe = {red_jpeg, sizeof(red_jpeg), 0U, 0U, false};
    JDEC decoder;
    assert(jd_prepare(&decoder, feed, work, sizeof(work), &probe) == JDR_OK);
    assert(jd_decomp(&decoder, collect, 0) == JDR_OK);
    assert(probe.seen);

    const unsigned red = (probe.pixel >> 11) & 0x1FU;
    const unsigned green = (probe.pixel >> 5) & 0x3FU;
    const unsigned blue = probe.pixel & 0x1FU;
    /* Loose bounds rather than an exact word: JPEG is lossy, and the point is
     * which channel the colour landed in, not the last bit of it. */
    assert(red >= 28U);
    assert(blue <= 3U);
    assert(green <= 8U);

    printf("album art decode tests passed\n");
    return 0;
}
